"""Learn the rail geometry from a running Factorio 2.0 server and write src/factorio_agent_mcp/data/rail_table.json.

For every rail piece and direction it places the piece in an empty sandbox, tries all candidate pieces around each open end
and keeps those the game reports as connected (LuaRailEnd.move_forward). Run it again after a Factorio update, then
run tools/gen_rail_table.py to regenerate the Lua table of the mod.

    python tools/calibrate_rails.py --password geheim [--host 127.0.0.1 --port 27015] [--sandbox 4001 4001]

It needs generated chunks at the sandbox position and removes everything it builds. Runs a few seconds per piece type
(the game is busy meanwhile), so do not run it while people play.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from factorio_agent_mcp.rcon import Rcon  # noqa: E402

TYPES = ["straight-rail", "half-diagonal-rail", "curved-rail-a", "curved-rail-b"]
LUA = (pathlib.Path(__file__).with_name("calibrate_rails.lua")).read_text()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=27015)
    ap.add_argument("--password", required=True)
    ap.add_argument("--sandbox", type=int, nargs=2, default=[4001, 4001], metavar=("X", "Y"), help="odd tile coordinates")
    args = ap.parse_args()
    cx, cy = args.sandbox
    rcon = Rcon(args.host, args.port, args.password, timeout=600)
    rcon.command(f"/silent-command local s = game.surfaces[1]; s.request_to_generate_chunks({{{cx}, {cy}}}, 3); s.force_generate_chunk_requests()")
    pieces: dict = {}
    version = rcon.command("/silent-command rcon.print(helpers.table_to_json({v = script.active_mods.base}))")
    for name in TYPES:
        code = LUA.replace("@SEED@", name)
        code = re.sub(r"local cx,cy=\d+,\d+", f"local cx,cy={cx},{cy}", code)
        out = rcon.command("/silent-command " + code)
        data = json.loads(out)
        print(name, "pieces:", len(data["table"]), "candidates tried:", data["created"])
        pieces.update(data["table"])
    base = json.loads(version).get("v", "unknown")
    result = {"game_version": base, "pieces": pieces,
              "note": "Generated by tools/calibrate_rails.py from the real game. Key: 'type|direction'. Per end (front/back): "
                      "end_dir, end_rel [dx,dy] of the open end relative to the piece position, next: [turn, type, direction, dx, dy, "
                      "end_dir, end_dx, end_dy] for the piece that connects there (offsets relative to this piece's position)."}
    target = ROOT / "src" / "factorio_agent_mcp" / "data" / "rail_table.json"
    target.write_text(json.dumps(result, separators=(",", ":")))
    print("written", target, "- now run: python tools/gen_rail_table.py")


if __name__ == "__main__":
    main()
