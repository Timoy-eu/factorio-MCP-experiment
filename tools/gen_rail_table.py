"""Turn src/factorio_agent_mcp/data/rail_table.json (learned from the real game) into the Lua table
mod/fac_agent/scripts/rail_table.lua that the rail router loads.

Re-create the JSON with tools/calibrate_rails.py after a Factorio update, then run this script again.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "src/factorio_agent_mcp/data/rail_table.json").read_text())


def lua_end(e):
    nexts = ",\n".join(
        '        { "%s", "%s", %d, %d, %d, %d, %d, %d }' % tuple(n) for n in e["next"]
    )
    return '{ end_dir = %d, end_rel = { %d, %d }, next = {\n%s\n      } }' % (
        e["end_dir"], e["end_rel"][0], e["end_rel"][1], nexts)


lines = ["-- GENERATED by tools/gen_rail_table.py from rail_table.json (learned in Factorio %s). Do not edit." % data["game_version"],
         "-- pieces[\"type|direction\"].front/back = open end of the piece: end_dir, end_rel {dx,dy} and the pieces that connect there.",
         "-- next entry: { turn, type, direction, dx, dy, end_dir, end_dx, end_dy } (offsets relative to this piece, end = far end of the next piece).",
         "return {", '  version = "%s",' % data["game_version"], "  pieces = {"]
for key in sorted(data["pieces"]):
    p = data["pieces"][key]
    lines.append('    ["%s"] = {\n      front = %s,\n      back = %s,\n    },' % (key, lua_end(p["front"]), lua_end(p["back"])))
lines += ["  },", "}", ""]
(ROOT / "mod/fac_agent/scripts/rail_table.lua").write_text("\n".join(lines))
print("ok", len(data["pieces"]), "pieces")
